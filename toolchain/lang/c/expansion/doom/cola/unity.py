print('')
print('unity: esto es para ITERAR. `out/doom.bex` no lleva icono ni se')
print('       despliega. Para JUGAR:  bmo.ps1  -- compila DOOM directo a')
print('       staging/BMO-DATA/apps/, le pone la cara y lo deja listo.')

# Y el codigo de salida se propaga, que es lo que faltaba.
if proc.returncode != 0:
    sys.exit("unity: NO se construyo doom.bex (codigo %d)" % proc.returncode)

